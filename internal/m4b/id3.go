func decodeByte(b byte, table *[128]rune) rune {
	if b < 0x80 {
		return rune(b)
	}
	return table[b-0x80]
}

func pickBestCyrillic(b []byte) string {
	if utf8.Valid(b) {
		s := string(b)
		if scoreCyrillicString(s) > 0 {
			return strings.TrimSpace(s)
		}
	}

	bestScore := -1
	bestStr := string(b)

	encodings := []*[128]rune{
		&tableWindows1251,
		&tableKOI8R,
		&tableCP866,
		&tableISO8859_5,
	}

	for _, table := range encodings {
		runes := make([]rune, len(b))
		for i, v := range b {
			runes[i] = decodeByte(v, table)
		}
		str := string(runes)
		score := scoreCyrillicString(str)

		if score > bestScore {
			bestScore = score
			bestStr = str
		}
	}

	return strings.TrimSpace(strings.TrimRight(bestStr, "\x00"))
}

func scoreCyrillicString(str string) int {
	score := 0
	for _, r := range str {
		switch {
		case (r >= 'А' && r <= 'Я') || (r >= 'а' && r <= 'я') || r == 'Ё' || r == 'ё':
			score += 5
		case r >= 32 && r <= 126:
			score++
		case r == '\uFFFD':
			score -= 100
		}
	}
	return score
}
